"""Generate Rust and Go protobuf bindings from the pinned protoc descriptor.

The pinned generators are protoc 33.5 and protoc-gen-go v1.36.8. They are taken
from --protoc and --go-plugin, then from the PROTOC and PROTOC_GEN_GO
environment variables, and otherwise from PATH.
"""
import argparse
from pathlib import Path
import os
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
GO_MODULE_ROOT = "github.com/Oraclizer/oip-spec"
SCHEMA = "proto/oip.proto"
RUST = Path("src/wire/generated.rs")
GO = Path("go/wirepb/oip.pb.go")
HEADER = "// Generated by scripts/generate-wire.py from proto/oip.proto. Do not edit.\n"

def varint(data, offset):
    value = 0
    for shift in range(0, 70, 7):
        if offset == len(data):
            raise ValueError("truncated descriptor varint")
        byte = data[offset]
        offset += 1
        value |= (byte & 127) << shift
        if byte < 128:
            return value, offset
    raise ValueError("descriptor varint too wide")

def fields(data):
    offset = 0
    result = {}
    while offset < len(data):
        key, offset = varint(data, offset)
        tag, kind = key >> 3, key & 7
        if kind == 0:
            value, offset = varint(data, offset)
        elif kind == 2:
            size, offset = varint(data, offset)
            value = data[offset:offset + size]
            if len(value) != size:
                raise ValueError("truncated descriptor field")
            offset += size
        else:
            raise ValueError("unexpected descriptor wire type")
        result.setdefault(tag, []).append(value)
    return result

def one(node, tag):
    values = node[tag]
    if len(values) != 1:
        raise ValueError("ambiguous descriptor field")
    return values[0]

def name(node, tag=1):
    return one(node, tag).decode("ascii")

def camel(identifier):
    return "".join(part.capitalize() for part in identifier.split("_"))

def snake(identifier):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", identifier).lower()

def scalar(field):
    kind = one(field, 5)
    types = {4: ("uint64", "u64"), 6: ("fixed64", "u64"), 8: ("bool", "bool"),
             12: ('bytes = "vec"', "Vec<u8>")}
    if kind == 11:
        return "message", name(field, 6).rsplit(".", 1)[1]
    return types[kind]

def rust_file(descriptor):
    file = fields(one(fields(descriptor), 1))
    assert name(file) == SCHEMA
    output = [HEADER.rstrip(), ""]
    for message_bytes in file[4]:
        message = fields(message_bytes)
        message_name = name(message)
        modules = [fields(data) for data in message.get(8, [])]
        groups = [[] for _ in modules]
        ordinary = []
        for data in message[2]:
            field = fields(data)
            if 9 in field:
                groups[one(field, 9)].append(field)
            else:
                ordinary.append(field)
        output.extend(["#[derive(Clone, PartialEq, ::prost::Message)]",
                       f"pub struct {message_name} {{"])
        for field in ordinary:
            tag = one(field, 3)
            prost_type, rust_type = scalar(field)
            label = one(field, 4)
            if label == 3:
                qualifier = "repeated"
                if one(field, 5) == 6:
                    assert one(fields(one(field, 8)), 2) == 0
                    qualifier += ', packed = "false"'
                rust_type = f"Vec<{rust_type}>"
            elif label == 1:
                qualifier = "optional"
                rust_type = f"Option<{rust_type}>"
            else:
                raise ValueError("unexpected protobuf label")
            output.extend([f'    #[prost({prost_type}, {qualifier}, tag = "{tag}")]',
                           f"    pub {name(field)}: {rust_type},"])
        for group, descriptor_group in zip(groups, modules):
            group_name = name(descriptor_group)
            rust_type = f"{snake(message_name)}::{camel(group_name)}"
            tags = ", ".join(str(one(field, 3)) for field in group)
            output.extend([f'    #[prost(oneof = "{rust_type}", tags = "{tags}")]',
                           f"    pub {group_name}: Option<{rust_type}>,"])
        output.extend(["}", ""])
        if modules:
            output.append(f"pub mod {snake(message_name)} {{")
            for group, descriptor_group in zip(groups, modules):
                output.extend(["    #[derive(Clone, PartialEq, ::prost::Oneof)]",
                               f"    pub enum {camel(name(descriptor_group))} {{"])
                for field in group:
                    tag = one(field, 3)
                    prost_type, rust_type = scalar(field)
                    if prost_type == "message":
                        rust_type = f"super::{rust_type}"
                    output.extend([f'        #[prost({prost_type}, tag = "{tag}")]',
                                   f"        {camel(name(field))}({rust_type}),"])
                output.append("    }")
            output.extend(["}", ""])
    return "\n".join(output).encode("utf-8")

def run(command):
    return subprocess.run(command, cwd=ROOT, check=True, capture_output=True).stdout.strip()

def tool(explicit, variable, program):
    located = explicit or os.environ.get(variable) or shutil.which(program)
    if not located:
        raise SystemExit(f"{program} not found: pass its path or set {variable}")
    return Path(located)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--protoc", type=Path)
    parser.add_argument("--go-plugin", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    args.protoc = tool(args.protoc, "PROTOC", "protoc")
    args.go_plugin = tool(args.go_plugin, "PROTOC_GEN_GO", "protoc-gen-go")
    if run([args.protoc, "--version"]) != b"libprotoc 33.5":
        raise SystemExit("protoc 33.5 required")
    if run([args.go_plugin, "--version"]) not in (b"protoc-gen-go v1.36.8", b"protoc-gen-go.exe v1.36.8"):
        raise SystemExit("protoc-gen-go 1.36.8 required")
    (ROOT / "target").mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="wire-generate-", dir=ROOT / "target") as temporary:
        target = Path(temporary)
        descriptor = target / "schema.pb"
        run([args.protoc, f"--descriptor_set_out={descriptor}", SCHEMA])
        run([args.protoc, f"--plugin=protoc-gen-go={args.go_plugin}", f"--go_out={target}",
             f"--go_opt=module={GO_MODULE_ROOT}", SCHEMA])
        files = {RUST: rust_file(descriptor.read_bytes()), GO: (target / GO).read_bytes()}
        for relative, content in files.items():
            path = ROOT / relative
            if args.check:
                if path.read_bytes() != content:
                    raise SystemExit(f"generated bytes differ: {relative}")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(content)
    print("Rust and Go generated bindings match the pinned schema.")

if __name__ == "__main__":
    main()
