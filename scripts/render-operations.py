"""Check spec/operations.json and render its name view, spec/operations.md."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = Path("spec/operations.json")
VIEW = Path("spec/operations.md")
HEADER = "<!-- Generated by scripts/render-operations.py from spec/operations.json. Do not edit. -->"


def fail(message):
    raise SystemExit(f"{TABLE.as_posix()}: {message}")


def unique_keys(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            fail(f"duplicate key {key!r}")
        result[key] = value
    return result


def cell(text):
    return text.replace("|", "\\|")


def code_list(values, codes):
    return ", ".join(f"{code} {values[code]}" for code in codes)


class Table:
    def __init__(self, data):
        self.data = data
        self.enums = {}
        for name, enum in data["enums"].items():
            values = {}
            for value in enum["values"]:
                if value["code"] in values or value["name"] in values.values():
                    fail(f"enum {name} repeats a code or name")
                values[value["code"]] = value["name"]
            self.enums[name] = values
        self.response = {value["code"]: value for value in data["enums"]["response_code"]["values"]}
        kinds = self.enums["response_kind"]
        for value in self.response.values():
            if value.get("kind") not in kinds or not isinstance(value.get("commit"), bool):
                fail(f"response code {value['code']} needs a known kind and a commit flag")
        self.response_names = {value["name"]: value for value in self.response.values()}
        for value in data["enums"]["family"]["values"]:
            if "body_field" not in value:
                fail(f"family {value['code']} has no body field")

    def enum(self, name):
        if name not in self.enums:
            fail(f"unknown enum {name!r}")
        return self.enums[name]

    def accepted(self, field, where):
        values = self.enum(field["enum"])
        accepted = field["accepted"]
        if accepted == "any":
            return "Accepted: any value."
        if accepted == "all":
            if not values:
                fail(f"{where}: enum {field['enum']} has no codes to accept")
            return "Accepted: every listed code."
        unknown = [code for code in accepted if code not in values]
        if unknown:
            fail(f"{where}: codes {unknown} are not in enum {field['enum']}")
        return f"Accepted: {code_list(values, accepted)}."

    def word_type(self, field, where):
        kind = field["type"]
        if kind not in self.data["word_types"]:
            fail(f"{where}: unknown word type {kind!r}")
        if kind == "code":
            self.enum(field["enum"])
            return f"`{field['enum']}` code"
        return f"`{kind}`"

    def expand(self, fields, where, prefix="", condition=None, groups=()):
        rows = []
        for field in fields:
            kind = field["kind"]
            if kind == "use":
                group = field["group"]
                if group not in self.data["groups"]:
                    fail(f"{where}: unknown group {group!r}")
                if group in groups:
                    fail(f"{where}: group {group!r} uses itself")
                rows += self.expand(self.data["groups"][group]["fields"], where, prefix,
                                    condition, groups + (group,))
                continue
            path = prefix + field["name"]
            note = field.get("description", "")
            once = "1" if condition is None else f"1 if `{condition}` is 1"
            many = "N" if condition is None else f"N if `{condition}` is 1"
            if kind == "word":
                text = " ".join(part for part in [note, self.accepted(field, where)
                                                  if field["type"] == "code" else ""] if part)
                rows.append(dict(path=path, count=once, type=self.word_type(field, where), text=text,
                                 word=field))
            elif kind == "optional":
                rows.append(dict(path=path, count=once, type="presence",
                                 text=" ".join(part for part in ["0 absent, 1 present.", note] if part)))
                rows += self.expand(field["fields"], where, path + ".", path, groups)
            elif kind == "counted_set":
                item = field["item"]
                accepted = self.accepted(item, where) if item["type"] == "code" else ""
                rows.append(dict(path=path, count=once, type="count",
                                 text=" ".join(part for part in ["Number of items N.", note] if part)))
                rows.append(dict(path=path + "[]", count=many, type=self.word_type(item, where),
                                 text=" ".join(part for part in ["Strictly ascending.", accepted] if part)))
            elif kind == "counted_pairs":
                first, second = field["first"], field["second"]
                rows.append(dict(path=path, count=once, type="count", text=" ".join(
                    part for part in [f"Number of entries N. Each entry is `{first['name']}` then "
                                      f"`{second['name']}`.", note] if part)))
                for member, text in [(first, "Strictly ascending."), (second, "")]:
                    accepted = self.accepted(member, where) if member["type"] == "code" else ""
                    rows.append(dict(path=f"{path}[].{member['name']}", count=many,
                                     type=self.word_type(member, where),
                                     text=" ".join(part for part in [text, accepted] if part)))
            elif kind == "tagged":
                values = self.enum(field["enum"])
                codes = [case["code"] for case in field["cases"]]
                if sorted(codes) != codes or set(codes) != set(values):
                    fail(f"{where}: cases of {path} must list every {field['enum']} code in order")
                cases = [(case["code"], values[case["code"]],
                          self.expand(case["fields"], where, path + ".", condition, groups))
                         for case in field["cases"]]
                rows.append(dict(path=path, count=once, type=f"`{field['enum']}` code", cases=cases,
                                 text=" ".join(part for part in [
                                     "Selects a case; the words of that case end the layout.", note] if part)))
            else:
                fail(f"{where}: unknown field kind {kind!r}")
        return rows

    def check_operation(self, operation, rows):
        where = operation["name"]
        paths = [row["path"] for row in rows]
        layouts = [paths]
        for row in rows:
            for _, _, case_rows in row.get("cases", []):
                layouts.append(paths + [case_row["path"] for case_row in case_rows])
        if any(len(layout) != len(set(layout)) for layout in layouts):
            fail(f"{where}: repeated field path")
        if any("cases" in row for row in rows[:-1]):
            fail(f"{where}: a tagged field must be last")
        target = operation.get("target_domain")
        if target is not None and not any(
                row["path"] == target and row.get("word", {}).get("type") == "domain_id"
                and row["count"] == "1" for row in rows):
            fail(f"{where}: target_domain {target!r} is not a top-level domain word")
        for blob in operation["blobs"]:
            if blob["type"] not in self.data["blob_types"]:
                fail(f"{where}: unknown blob type {blob['type']!r}")
        names = [blob["name"] for blob in operation["blobs"]]
        if len(names) != len(set(names)):
            fail(f"{where}: repeated blob name")
        for check in operation.get("checks", []):
            if check["error"] not in self.response_names:
                fail(f"{where}: unknown error {check['error']!r}")
        codes = operation.get("recorded_codes", [])
        if codes != sorted(codes) or any(self.response.get(code, {}).get("kind") != 1 for code in codes):
            fail(f"{where}: recorded codes must be ascending recorded response codes")


def load():
    data = json.loads((ROOT / TABLE).read_text(encoding="utf-8"), object_pairs_hook=unique_keys)
    if data.get("table_format") != 1:
        fail("unsupported table_format")
    table = Table(data)
    refusal = data["reference_profile"]["unsupported_operation_refusal"]
    if table.response_names.get(refusal, {}).get("kind") != 3:
        fail(f"reference refusal {refusal!r} is not a refusal code")
    families = table.enum("family")
    operations, seen = [], {}
    for operation in data["operations"]:
        family, opcode = operation["family"], operation["opcode"]
        if family not in families:
            fail(f"{operation['name']}: unknown family {family}")
        if opcode != seen.get(family, 0) + 1 or (seen and family < max(seen)):
            fail(f"{operation['name']}: operations must be in family order with opcodes 1, 2, 3, ...")
        seen[family] = opcode
        rows = table.expand(operation["words"], operation["name"])
        table.check_operation(operation, rows)
        operations.append((operation, rows))
    if set(seen) != set(families):
        fail("every family needs at least one operation")
    for key in ("name", "title"):
        values = [operation[key] for operation in data["operations"]]
        if len(values) != len(set(values)):
            fail(f"operation {key}s must be unique")
    return table, operations, [seen[family] for family in sorted(families)]


def render(table, operations, counts):
    data = table.data
    families = {value["code"]: value for value in data["enums"]["family"]["values"]}
    accepted = [operation for operation, _ in operations if operation["reference_accepts"]]
    refused = [operation for operation, _ in operations if not operation["reference_accepts"]]
    out = [HEADER, f"# {data['title']}", "", data["summary"], "",
           "The table is [operations.json](operations.json) and its format is "
           "[operations.schema.json](operations.schema.json). This name view is generated from the "
           "table by `python scripts/render-operations.py`; edit the table, not this file. The "
           "specification name of an operation is its name in the family table of "
           "[wire-conformance.md](wire-conformance.md).", "",
           "## Layout rules", ""]
    out += [f"- {rule}" for rule in data["layout_rules"]]
    record = data["operation_record"]
    out += ["", "## Operation record", "", record["order"], "",
            "| Tag | Field | Wire type | Label | Description |", "|---|---|---|---|---|"]
    out += [f"| {field['tag']} | `{field['name']}` | {field['wire_type']} | {field['label']} | "
            f"{cell(field['description'])} |" for field in record["fields"]]
    out += ["", "## Deadline modes", "", "| Mode | Meaning |", "|---|---|"]
    out += [f"| `{mode}` | {cell(text)} |" for mode, text in data["deadline_modes"].items()]
    out += ["", "## Operations", "",
            f"{len(operations)} operations. Families 1 through {len(counts)} have "
            f"{', '.join(str(count) for count in counts)} operations in opcode order.", "",
            "| Family | Opcode | Operation | Specification name | Reference accepts | Call | Blobs | Deadline |",
            "|---|---|---|---|---|---|---|---|"]
    for operation, _ in operations:
        family = families[operation["family"]]
        out.append(f"| {family['code']} {family['name']} | {operation['opcode']} | "
                   f"[{operation['name']}](#{operation['name'].lower()}) | {operation['title']} | "
                   f"{'yes' if operation['reference_accepts'] else 'no'} | "
                   f"{'yes' if operation['call'] else 'no'} | {len(operation['blobs'])} | "
                   f"`{operation['deadline']}` |")
    profile = data["reference_profile"]
    out += ["", "## Reference configuration", "", profile["description"], "",
            f"Accepted: {len(accepted)} of {len(operations)} operations. Refused with "
            f"{profile['unsupported_operation_refusal']}: "
            f"{', '.join(operation['name'] for operation in refused)}.", "",
            "## Responses", "", data["responses"]["call_identifier"], "",
            data["responses"]["delivery_and_refusal"]]
    for code, family in sorted(families.items()):
        members = [(operation, rows) for operation, rows in operations if operation["family"] == code]
        out += ["", f"## Family {code} {family['name']}", "",
                f"Core body field `{family['body_field']}` (tag {15 + code}). "
                f"{len(members)} operations.", ""]
        for operation, rows in members:
            out += render_operation(table, operation, rows, family)
    out += ["## Shared groups", "", "| Group | Used by | Description |", "|---|---|---|"]
    for name, group in data["groups"].items():
        users = [operation["name"] for operation, _ in operations
                 if any(field.get("group") == name for field in operation["words"])]
        out.append(f"| `{name}` | {', '.join(users)} | {cell(group['description'])} |")
    out += ["", "## Word types", "", "All words are 64-bit fixed-width values on the wire.", "",
            "| Type | Description |", "|---|---|"]
    out += [f"| `{name}` | {cell(kind['description'])} |" for name, kind in data["word_types"].items()]
    out += ["", "## Blob types", "", "| Type | Length | Description |", "|---|---|---|"]
    for name, kind in data["blob_types"].items():
        length = str(kind["length"]) if "length" in kind else f"at least {kind['min_length']}"
        out.append(f"| `{name}` | {length} | {cell(kind['description'])} |")
    out += ["", "## Enums", ""]
    for name, enum in data["enums"].items():
        out += [f"### {name}", "", enum["description"], ""]
        if "range" in enum:
            out += [f"Accepted range: {enum['range']['min']} through {enum['range']['max']}.", ""]
        values = enum["values"]
        if not values:
            out += ["No named codes.", ""]
            continue
        extra = [key for key in ("body_field", "kind", "commit", "description")
                 if any(key in value for value in values)]
        titles = {"body_field": "Body field", "kind": "Kind", "commit": "Commit", "description": "Description"}
        out += ["| " + " | ".join(["Code", "Name"] + [titles[key] for key in extra]) + " |",
                "|" + "---|" * (2 + len(extra))]
        for value in values:
            items = [str(value["code"]), value["name"]]
            for key in extra:
                item = value.get(key, "")
                if key == "kind":
                    item = f"{item} {table.enums['response_kind'][item]}"
                elif key == "commit":
                    item = "present" if item else "absent"
                elif key == "body_field":
                    item = f"`{item}`"
                items.append(cell(item))
            out.append("| " + " | ".join(items) + " |")
        out.append("")
    lines = [line for index, line in enumerate(out) if line or (index and out[index - 1])]
    return "\n".join(lines).rstrip("\n") + "\n"


def render_operation(table, operation, rows, family):
    data = table.data
    out = [f"### {operation['name']}", "",
           f"Family {family['code']} {family['name']}, opcode {operation['opcode']}, specification name "
           f"\"{operation['title']}\". {operation['summary']}", ""]
    accepts = "accepted" if operation["reference_accepts"] else (
        f"not accepted; refused with {data['reference_profile']['unsupported_operation_refusal']}")
    facts = [f"Reference configuration: {accepts}."]
    if "reference_note" in operation:
        facts[0] += " " + operation["reference_note"]
    facts.append(f"Deadline: `{operation['deadline']}`. {data['deadline_modes'][operation['deadline']]}")
    if "target_domain" in operation:
        facts.append(f"Target: the Core `target_domain` MUST equal `{operation['target_domain']}`, "
                     "otherwise INVALID_SOURCE.")
    if operation["call"]:
        codes = code_list(table.enums["response_code"], operation["recorded_codes"])
        facts.append(f"Call: yes. Recorded codes: {codes}. Delivery and refusal codes also apply.")
    else:
        facts.append("Call: no. It has no correlated response.")
    out += [f"- {fact}" for fact in facts] + [""]
    if rows:
        out += ["Words:", "", "| Order | Field | Count | Type | Description |", "|---|---|---|---|---|"]
        out += [f"| {index} | `{row['path']}` | {row['count']} | {row['type']} | {cell(row['text'])} |"
                for index, row in enumerate(rows, 1)]
        out.append("")
        for row in rows:
            if "cases" in row:
                out += [f"Cases of `{row['path']}`:", "", "| Tag | Case | Words after the tag |", "|---|---|---|"]
                for code, name, case_rows in row["cases"]:
                    words = ", ".join(f"`{case['path']}` {case['type']}" for case in case_rows)
                    out.append(f"| {code} | {name} | {words} |")
                out.append("")
    else:
        out += ["Words: none.", ""]
    if operation["blobs"]:
        out += ["Blobs:", "", "| Order | Field | Type | Description |", "|---|---|---|---|"]
        out += [f"| {index} | `{blob['name']}` | `{blob['type']}` | {cell(blob.get('description', ''))} |"
                for index, blob in enumerate(operation["blobs"], 1)]
        out.append("")
    else:
        out += ["Blobs: none.", ""]
    if operation.get("checks"):
        out += ["Checks:", ""]
        out += [f"- {check['when']}: {check['rule']} Otherwise {check['error']}."
                for check in operation["checks"]]
        out.append("")
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if spec/operations.md is not current")
    args = parser.parse_args()
    table, operations, counts = load()
    content = render(table, operations, counts).encode("utf-8")
    path = ROOT / VIEW
    if args.check:
        if not path.exists() or path.read_bytes() != content:
            raise SystemExit(f"{VIEW.as_posix()} differs from {TABLE.as_posix()}; "
                             "run python scripts/render-operations.py")
    else:
        path.write_bytes(content)
    print(f"{VIEW.as_posix()} matches {TABLE.as_posix()}: {len(operations)} operations, "
          f"family counts {counts}.")


if __name__ == "__main__":
    main()
